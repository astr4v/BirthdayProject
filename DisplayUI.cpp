void initDisplay() {
  if(!display.begin(SSD1306_SWITCHCAPVCC, OLED_I2C_ADDR)) {
    Serial.println(F("OLED gagal inisialisasi"));
    for(;;);
  }
  display.clearDisplay();
  display.display();
}


